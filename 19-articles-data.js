        function calculateCryptoPnL() {
            const buyPrice = parseFloat(document.getElementById('pnl-buy-price').value) || 0;
            const sellPrice = parseFloat(document.getElementById('pnl-sell-price').value) || 0;
            const amount = parseFloat(document.getElementById('pnl-amount').value) || 0;
            const totalBuy = buyPrice * amount;
            const totalSell = sellPrice * amount;
            const profitLoss = totalSell - totalBuy;
            const roi = totalBuy > 0 ? (profitLoss / totalBuy) * 100 : 0;
            const resAmountEl = document.getElementById('pnl-result-amount');
            const resRoiEl = document.getElementById('pnl-result-roi');
            if (profitLoss >= 0) {
                resAmountEl.className = "text-lg font-bold text-emerald-400";
                resRoiEl.className = "text-base font-bold text-emerald-400";
                resAmountEl.innerText = `+$${profitLoss.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
                resRoiEl.innerText = `+${roi.toFixed(2)}%`;
            } else {
                resAmountEl.className = "text-lg font-bold text-rose-400";
                resRoiEl.className = "text-base font-bold text-rose-400";
                resAmountEl.innerText = `-$${Math.abs(profitLoss).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
                resRoiEl.innerText = `${roi.toFixed(2)}%`;
            }
        }
