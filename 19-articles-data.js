        function startAutomaticChartUpdates() {
            setInterval(() => {
                const nowTime = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
                if (stockSectorBarChartInstance) {
                    const sectorData = stockSectorBarChartInstance.data.datasets[0].data;
                    for (let i = 0; i < sectorData.length; i++) {
                        let fluctuation = (Math.random() - 0.49) * 1.2;
                        sectorData[i] = Math.max(8, Math.min(40, parseFloat((sectorData[i] + fluctuation).toFixed(1))));
                    }
                    stockSectorBarChartInstance.update('none');
                }
                if (cryptoIndexChartInstance) {
                    const candleSet = cryptoIndexChartInstance.data.datasets[0].data;
                    const lineSet = cryptoIndexChartInstance.data.datasets[1].data;
                    const volumeSet = cryptoIndexChartInstance.data.datasets[2].data;
                    const lastCandle = candleSet[candleSet.length - 1];
                    const base = lastCandle.c;
                    const open = base;
                    const close = Math.max(100, base + (Math.random() - 0.47) * 45);
                    const high = Math.max(open, close) + Math.random() * 24;
                    const low = Math.min(open, close) - Math.random() * 24;
                    const stamp = Date.now();
                    candleSet.shift();
                    candleSet.push({x: stamp, o: open, h: high, l: low, c: close});
                    lineSet.shift();
                    lineSet.push({x: stamp, y: close});
                    volumeSet.shift();
                    volumeSet.push({x: stamp, y: 16 + Math.random() * 16});
                    cryptoIndexChartInstance.update('none');
                    const newVal = close;
                    const indexValEl = document.getElementById('live-index-val');
                    if (indexValEl) indexValEl.innerText = `$${newVal.toLocaleString('en-US', { minimumFractionDigits: 2 })}`;
                }
                /* Intraday Telemetry kini berjalan otomatis lewat timer internalnya sendiri. */
                if (globalMarketChartInstance) {
                    const globalLabels = globalMarketChartInstance.data.labels;
                    const globalData = globalMarketChartInstance.data.datasets[0].data;
                    globalLabels.shift();
                    globalLabels.push(nowTime);
                    globalData.shift();
                    const lastGlobalVal = globalData[globalData.length - 1];
                    const newGlobalVal = parseFloat((lastGlobalVal + (Math.random() - 0.48) * 3).toFixed(2));
                    globalData.push(newGlobalVal);
                    globalMarketChartInstance.update('none');
                }
                if (macroBarChartInstance) {
                    // Gerakkan empat titik secara otomatis tanpa mengubah
                    // struktur/fungsi chart lain pada halaman.
                    const scatterRanges = [
                        { minX: 30, maxX: 42, minY: 62, maxY: 82 },
                        { minX: 17, maxX: 29, minY: 45, maxY: 63 },
                        { minX: 11, maxX: 21, minY: 30, maxY: 47 },
                        { minX: 7,  maxX: 16, minY: 16, maxY: 34 }
                    ];
                    macroBarChartInstance.data.datasets.forEach((dataset, i) => {
                        const point = dataset.data[0];
                        const range = scatterRanges[i];
                        point.x = Math.max(
                            range.minX,
                            Math.min(range.maxX, point.x + (Math.random() - 0.5) * 1.4)
                        );
                        point.y = Math.max(
                            range.minY,
                            Math.min(range.maxY, point.y + (Math.random() - 0.5) * 2.4)
                        );
                    });
                    macroBarChartInstance.update('none');
                }
                if (globalMiniTickChartInstance) {
                    const miniData = globalMiniTickChartInstance.data.datasets[0].data;
                    miniData.shift();
                    const lastMini = miniData[miniData.length - 1];
                    miniData.push(parseFloat((lastMini + (Math.random() - 0.48) * 2).toFixed(2)));
                    globalMiniTickChartInstance.update('none');
                }
            }, 2000);
        }
